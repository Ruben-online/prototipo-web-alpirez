-- Tabla de Inventario Principal
create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  code varchar(50) unique,
  name varchar(100) not null,
  description text default '',
  category_id bigint references public.categories(id) on delete set null,
  brand_id bigint references public.brands(id) on delete set null,
  unit_id bigint references public.units(id) on delete set null,
  stock integer default 0 check (stock >= 0),
  min_stock integer default 5 check (min_stock >= 0),
  unit_price decimal(10, 2) default 0.00 check (unit_price >= 0),
  status text default 'Disponible' check (status in ('Disponible', 'Agotado', 'Bajo stock')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Trigger para actualizar automáticamente el estado (Disponible/Agotado) según el stock
create or replace function public.handle_inventory_status()
returns trigger language plpgsql as $$
begin
  if new.stock <= 0 then new.status := 'Agotado';
  elsif new.stock <= new.min_stock then new.status := 'Bajo stock';
  else new.status := 'Disponible';
  end if;
  return new;
end; $$;

drop trigger if exists inventory_stock_status_trigger on public.inventory;
create trigger inventory_stock_status_trigger
  before insert or update of stock, min_stock on public.inventory
  for each row execute function public.handle_inventory_status();

