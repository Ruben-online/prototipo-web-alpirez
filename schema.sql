-- 1. EXTENSIONES (Necesaria para validación de choques de horario en citas)
create extension if not exists btree_gist;

-- 2. FUNCIÓN PARA ACTUALIZAR FECHAS DE MODIFICACIÓN (updated_at)
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end; $$;

-- ========================================================
-- MÓDULO DE PACIENTES Y CONSULTAS
-- ========================================================

-- Tabla de Pacientes
create table if not exists public.patients (
  id bigint generated by default as identity primary key,
  full_name varchar(100) not null,
  birth_date date not null check (birth_date <= current_date),
  sex text not null check (sex in ('Femenino', 'Masculino', 'Otro', 'Prefiere no indicar')),
  phone varchar(20) not null,
  email varchar(120) not null unique,
  address varchar(250),
  status text not null default 'Activo' check (status in ('Activo', 'Inactivo')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tabla de Historia Médica (Relación 1:1 con Pacientes)
create table if not exists public.patient_medical_history (
  patient_id bigint primary key references public.patients (id) on delete cascade,
  allergies text not null default '',
  conditions text not null default '',
  medications text not null default '',
  dermatological_history text not null default '',
  observations text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Tabla de Consultas Médicas
create table if not exists public.consultations (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients (id) on delete restrict,
  consultation_date date not null default current_date,
  reason varchar(150) not null,
  diagnosis text not null,
  treatment text not null default '',
  observations text not null default '',
  follow_up_date date check (follow_up_date is null or follow_up_date >= consultation_date),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Trigger para crear automáticamente la historia médica al registrar un paciente
create or replace function public.handle_new_patient()
returns trigger language plpgsql security definer as $$
begin
  insert into public.patient_medical_history (patient_id) values (new.id);
  return new;
end; $$;

drop trigger if exists on_patient_created on public.patients;
create trigger on_patient_created
  after insert on public.patients
  for each row execute function public.handle_new_patient();

-- ========================================================
-- MÓDULO DE CITAS (APPOINTMENTS)
-- ========================================================

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  patient_id bigint not null references public.patients (id) on delete restrict,
  appointment_date date not null,
  start_time time not null,
  duration_minutes integer not null check (duration_minutes > 0),
  service text not null,
  status text not null default 'Confirmada' 
    check (status in ('Confirmada', 'Completada', 'Cancelada', 'No asistió')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  
  -- Validación para que no se solapen citas en la misma fecha/hora
  constraint appointments_no_overlap
    exclude using gist (
      tsrange(
        appointment_date + start_time,
        appointment_date + start_time + duration_minutes * interval '1 minute',
        '[)'
      ) with &&
    ) where (status in ('Confirmada', 'Completada'))
);

